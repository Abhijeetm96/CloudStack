export function getGlossaryTerm(termOrSlug: string): GlossaryTerm | undefined {
  const normalized = termOrSlug.toLowerCase().trim().replace(/\s+/g, '-').replace(/[^a-z0-9-]/g, '');
  if (DOCKER_GLOSSARY[normalized]) return DOCKER_GLOSSARY[normalized];
  
  // Search by exact term match
  const match = Object.values(DOCKER_GLOSSARY).find(
    (t) => t.term.toLowerCase() === termOrSlug.toLowerCase() || t.slug === normalized
  );
  if (match) return match;

  // Search by keyword substring
  return Object.values(DOCKER_GLOSSARY).find((t) =>
    t.term.toLowerCase().includes(termOrSlug.toLowerCase()) ||
    t.relatedTerms.some((r) => r.toLowerCase() === termOrSlug.toLowerCase())
  );
}

export function getAllGlossaryTerms(): GlossaryTerm[] {
  return Object.values(DOCKER_GLOSSARY);
}

export function searchGlossary(query: string): GlossaryTerm[] {
  const q = query.toLowerCase().trim();
  if (!q) return getAllGlossaryTerms();
  return Object.values(DOCKER_GLOSSARY).filter(
    (t) =>
      t.term.toLowerCase().includes(q) ||
      t.slug.toLowerCase().includes(q) ||
      t.simpleDefinition.toLowerCase().includes(q) ||
      t.technicalDefinition.toLowerCase().includes(q) ||
      t.analogy.toLowerCase().includes(q) ||
      t.commonConfusion.toLowerCase().includes(q) ||
      t.relatedTerms.some((r) => r.toLowerCase().includes(q))
  );
}
